/**
 * Terminal-Bench, current version (v1.1 N1). Since 2.0, Terminal-Bench tasks
 * use the Harbor task format, and the official runner is Harbor:
 *
 *   <task>/instruction.md        the prompt
 *   <task>/task.toml             [agent] timeout_sec, [verifier] timeout_sec, [environment] …
 *   <task>/environment/          Dockerfile (or docker-compose.yaml): the task image
 *   <task>/tests/test.sh         the verifier; it writes /logs/verifier/reward.txt (or reward.json)
 *   <task>/solution/solve.sh     the reference solution
 *
 * Two ways to run it:
 *  1. Natively (`tug bench terminal-bench --data <harbor tasks>`): each task runs
 *     in its own image with our docker isolation (G5). tests/ reaches the
 *     container (/tests, like Harbor) only after the agent has finished; then
 *     test.sh runs and the reward decides pass (reward ≥ 1).
 *  2. Through Harbor itself (`tug bench terminal-bench --harbor`): we write an
 *     "installed agent" adapter (`tugline_agent.py` + install template)
 *     that installs Tugline inside the task container and runs
 *     `tug -p … --mode yolo --json` there, then shell out to `harbor run`, and
 *     read Harbor's trial results back into a report. This is the official
 *     harness, so its numbers are the comparable ones.
 */
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

/** Minimal TOML reader for task.toml: [section] headers and key = value (strings, numbers, booleans). */
export function miniToml(text: string): Record<string, Record<string, unknown>> {
  const out: Record<string, Record<string, unknown>> = { '': {} };
  let sec = '';
  for (const raw of text.split('\n')) {
    const line = raw.replace(/\s+#.*$/, '').trim();
    if (!line || line.startsWith('#')) continue;
    const h = line.match(/^\[([^\]]+)\]$/);
    if (h) {
      sec = h[1].trim();
      out[sec] ??= {};
      continue;
    }
    const kv = line.match(/^([A-Za-z0-9_.-]+)\s*=\s*(.+)$/);
    if (!kv) continue;
    let v: unknown = kv[2].trim();
    const s = v as string;
    if (/^".*"$|^'.*'$/.test(s)) v = s.slice(1, -1);
    else if (/^-?\d+(\.\d+)?$/.test(s)) v = Number(s);
    else if (s === 'true' || s === 'false') v = s === 'true';
    out[sec][kv[1]] = v;
  }
  return out;
}

export function isHarborTask(dir: string): boolean {
  return fs.existsSync(path.join(dir, 'task.toml')) && fs.existsSync(path.join(dir, 'instruction.md'));
}

/** The WORKDIR of the task image (last WORKDIR in its Dockerfile), default /app. */
export function workdirOf(envDir: string): string {
  try {
    const df = fs.readFileSync(path.join(envDir, 'Dockerfile'), 'utf8');
    const all = [...df.matchAll(/^\s*WORKDIR\s+(\S+)/gim)].map((m) => m[1]);
    if (all.length) return all[all.length - 1];
  } catch {
    /* compose-only environment */
  }
  return '/app';
}

